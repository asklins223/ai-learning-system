/**
 * Agent 活动流：事件 → 用户可见文案映射（设计附录 A / B）。
 *
 * 红线（§3.1）：只取 safePayload 里的计数/ID/状态等结构化字段，
 * 字符串值一律本地映射。绝不把模型原文或 safePayload 的字符串值
 * 直接拼进文案。未知工具/角色按安全回退（"工具"/"代理"），不报错。
 */

import type { AgentEventView } from "@/lib/api";
import { isRecord } from "./note-editor-utils";

export type AgentEventRowStatus = "running" | "success" | "failed" | "warning" | "muted";

export interface AgentEventRowView {
  /** 前端渲染文案（固定中文模板，不含原始 payload 字符串值） */
  text: string;
  /** 状态点：进行中/成功/失败/警告/静默 */
  status: AgentEventRowStatus;
  /** 角色中文名（无角色时为 null） */
  roleLabel: string | null;
}

/** 角色中文名（附录 B）。未知角色返回 null，由调用方回退。 */
export function agentRoleLabel(role: string | null | undefined): string | null {
  if (!role) return null;
  return ROLE_LABELS[role] ?? null;
}

/** 工具中文名（附录 B 分组）。未知工具名安全回退为「工具」。 */
export function agentToolLabel(toolName: string | null | undefined): string {
  if (!toolName) return "工具";
  return TOOL_LABELS[toolName] ?? toolName;
}

/**
 * 事件 → 文案映射。
 *
 * 仅依赖 worker 实际写入的 5 种 eventType 字面量
 * （tool_request / tool_result / turn_completed / pagination_event /
 * validation_event）。其余（枚举里的 "aspirational" 类型）统一安全回退。
 */
export function agentEventRowText(event: AgentEventView): AgentEventRowView {
  const roleLabel = agentRoleLabel(event.agentRole);
  const payload = isRecord(event.safePayload) ? event.safePayload : {};
  switch (event.eventType) {
    case "tool_request":
      return toolRequestRow(event, payload, roleLabel);
    case "tool_result":
      return toolResultRow(event, payload, roleLabel);
    case "turn_completed":
      return turnCompletedRow(event, payload);
    case "pagination_event":
      return paginationRow(payload);
    case "validation_event":
      return validationRow(payload);
    default:
      return { text: "代理活动更新", status: "muted", roleLabel };
  }
}

