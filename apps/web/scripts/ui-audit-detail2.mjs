import { chromium } from "playwright";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
await page.goto("http://127.0.0.1:3000/login", { waitUntil: "networkidle" });
await page.fill('input[type="email"]', "owner@ailearn.local");
await page.fill('input[type="password"]', "ailearn_owner");
await page.click('button[type="submit"]');
await page.waitForURL((u) => !u.pathname.startsWith("/login"), { timeout: 20000 });
await page.goto("http://127.0.0.1:3000/learning-cards/aeaf059a-1e87-4121-a71b-c09ddf6fac25", { waitUntil: "networkidle" });
await page.waitForTimeout(1200);
await page.screenshot({ path: "/tmp/ui-audit/detail-real-card.png", fullPage: true });
console.log("shot ok");
await browser.close();
