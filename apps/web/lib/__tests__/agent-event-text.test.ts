describe("mergeAgentEvents — 去重与上限", () => {
  function ev(key: string): AgentEventView {
    return event({ eventKey: key, id: key, messageCode: key });
  }

  it("增量合并不产生重复事件", () => {
    const buffer = [ev("a"), ev("b")];
    const merged = mergeAgentEvents(buffer, [ev("b"), ev("c")], new Set());
    assert.deepEqual(merged.map((e) => e.eventKey), ["a", "b", "c"]);
  });

  it("超出上限丢弃最早事件", () => {
    const buffer = [ev("a"), ev("b")];
    const merged = mergeAgentEvents(buffer, [ev("c")], new Set(), 2);
    assert.deepEqual(merged.map((e) => e.eventKey), ["b", "c"]);
  });

  it("空增量返回原缓冲", () => {
    const buffer = [ev("a")];
    assert.equal(mergeAgentEvents(buffer, [], new Set()), buffer);
  });

  it("StrictMode 双调用更新函数不丢事件（回归）", () => {
    // React 19 dev（StrictMode）会以同一 prev 调用两次 setState 更新函数，
    // 用于检测不纯。如果合并逻辑依赖"seen 被副作用填充"，第二次调用会
    // 把结果清空，导致执行记录永远不显示。合并函数必须对入参只读。
    const buffer = [ev("a")];
    const page = [ev("b"), ev("c")];
    const seen = new Set<string>();
    // 第一次调用（React 内部 double-invoke 的第一遍）
    const r1 = mergeAgentEvents(buffer, page, seen);
    // 第二次调用：同一 prev + 同一 seen（合并函数不得修改 seen）
    const r2 = mergeAgentEvents(buffer, page, seen);
    assert.deepEqual(
      r1.map((e) => e.eventKey),
      ["a", "b", "c"],
      "第一次调用应正常合并",
    );
    assert.deepEqual(
      r2.map((e) => e.eventKey),
      ["a", "b", "c"],
      "第二次调用（同一入参）结果必须一致，不能因 seen 副作用清空",
    );
  });
});

describe("currentGenerationTask — 当前任务随活动流变化", () => {
  function runWith(stage: string | null): CardGenerationRunView {
    return {
      runId: "run-1",
      noteId: "note-1",
      noteVersionId: "nv-1",
      status: "running",
      stage: "running",
      stateVersion: 0,
      sequence: 1,
      engineMode: "supervisor_agent_v1",
      shellVersion: "v1",
      shellStage: stage,
      sourceSnapshot: { noteVersionId: "nv-1", versionNo: 3, contentHash: "h" },
      progress: { completed: 0, total: 100, unit: "percent" },
      coverage: {
        sourceUnitsCompleted: 0, sourceUnitsTotal: 1,
        imagesCompleted: 0, imagesTotal: 0,
        sourceCoverageBps: 0, imageCoverageBps: 10_000,
      },
      warnings: [],
      actions: { retryable: false, restartable: false, cancellable: true },
      result: null,
      error: null,
      createdAt: "2026-01-01T00:00:00Z",
      startedAt: null,
      finishedAt: null,
    };
  }

  it("有 running 事件时用事件文案描述当前任务", () => {
    const task = currentGenerationTask(
      runWith("generating"),
      event({
        eventType: "tool_request",
        eventKey: "e1",
        toolName: "delegate_specialist",
        agentRole: "generation_supervisor",
        turnNo: 2,
        safePayload: { args: { role: "text_extractor", bundleIds: ["a", "b", "c"] } },
      }),
    );
    assert.ok(task.title.startsWith("正在"), "进行中动作应加'正在'前缀");
    assert.ok(task.title.includes("委派"), "应包含事件动作文案");
    assert.ok(task.copy.includes("执行中"), "进行中应标记'执行中'");
  });

  it("有已完成事件时直接展示动作结果", () => {
    const task = currentGenerationTask(
      runWith("generating"),
      event({
        eventType: "tool_result",
        eventKey: "e2",
        toolName: "record_extraction_decisions",
        agentRole: "generation_supervisor",
        safePayload: { success: true, result: { candidateCount: 5 } },
      }),
    );
    assert.ok(!task.title.startsWith("正在"), "已完成事件不加'正在'前缀");
    assert.ok(task.title.includes("记录提取决策"), "应包含动作文案");
    assert.ok(task.copy.includes("已完成"), "已完成应标记'已完成'");
  });

  it("无事件时回退到阶段文案", () => {
    const task = currentGenerationTask(runWith("checking"), null);
    assert.equal(task.title, "正在检查结果质量");
    assert.equal(currentGenerationTask(runWith("preparing"), null).title, "正在理解这篇笔记");
    assert.equal(currentGenerationTask(runWith(null), null).title, "正在设计可回忆的问题");
  });
});

