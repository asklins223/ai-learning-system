describe("advanceEta — 预计剩余基于推进速率，不随 elapsed 单调膨胀", () => {
  it("percent 未到 15 时不估算（返回 null，不推进）", () => {
    const r = advanceEta(10, 60, null, null);
    assert.equal(r.remainingSeconds, null);
    assert.equal(r.sample, null);
    assert.equal(r.rate, null);
  });

  it("percent 100 时剩余为 0", () => {
    const r = advanceEta(100, 300, { elapsed: 240, percent: 80 }, 0.2);
    assert.equal(r.remainingSeconds, 0);
  });

  it("首个样本只记录，尚无速率 → 计算中", () => {
    const r = advanceEta(26, 30, null, null);
    assert.equal(r.remainingSeconds, null);
    assert.deepEqual(r.sample, { elapsed: 30, percent: 26 });
    assert.equal(r.rate, null);
  });

  it("percent 停留期间不推进样本，剩余时间保持不变（不虚涨）", () => {
    // 首次推进：样本 (30, 26)，速率未知
    const first = advanceEta(26, 30, null, null);
    // 二次推进：26→37，耗时 30s（30→60），速率 11/30 ≈ 0.367 %/s
    const jump = advanceEta(37, 60, first.sample, first.rate);
    assert.ok(jump.rate != null && jump.rate > 0);
    const etaAfterJump = jump.remainingSeconds;
    // percent 停在 37，elapsed 从 60 涨到 180：速率保持 → 剩余不变
    const stuck = advanceEta(37, 180, jump.sample, jump.rate);
    assert.equal(stuck.sample, jump.sample, "档位之间不推进样本");
    assert.equal(stuck.rate, jump.rate, "档位之间速率保持");
    assert.equal(stuck.remainingSeconds, etaAfterJump, "剩余时间不随 elapsed 膨胀");
  });

  it("再次推进时用 EWMA 平滑速率并更新剩余", () => {
    const first = advanceEta(26, 30, null, null); // 样本 (30, 26)
    const jump = advanceEta(37, 60, first.sample, null); // 26→37, dt=30 → rate=11/30
    assert.ok(jump.rate != null);
    const next = advanceEta(48, 120, jump.sample, jump.rate); // dp=11, dt=60 → instant≈0.183
    const expectedRate = jump.rate * 0.7 + (11 / 60) * 0.3;
    assert.ok(Math.abs((next.rate ?? 0) - expectedRate) < 1e-6, "速率应为 EWMA 平滑");
    assert.deepEqual(next.sample, { elapsed: 120, percent: 48 });
    assert.ok(next.remainingSeconds != null && next.remainingSeconds > 0);
  });
});
